# Aula 7 – Nível 1: Os operadores
# teste: 
a = 17                               # primeiro número
b = 5                                # segundo número
print("Soma:", a + b)                # 22
print("Subtração:", a - b)           # 12
print("Multiplicação:", a * b)       # 85
print("Divisão:", a / b)             # 3.4
print("Divisão inteira:", a // b)    # 3 (quantas vezes o 5 cabe inteiro no 17)
print("Resto:", a % b)               # 2 (o que sobra da divisão inteira)
print("Potência:", a ** 2)           # 289 (17 ao quadrado)
