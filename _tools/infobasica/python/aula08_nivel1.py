# Aula 8 – Nível 1: Verdadeiro ou falso
# teste: 
print(5 > 3)        # True: 5 é maior que 3
print(5 == 3)       # False: == compara se os dois são iguais
print(5 != 3)       # True: != significa "diferente"
nota = 8            # um valor de exemplo
print(nota >= 7)    # True: 8 é maior ou igual a 7
