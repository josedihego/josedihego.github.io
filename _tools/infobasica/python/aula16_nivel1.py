# Aula 16 – Nível 1: Contar com while
# teste: 
contador = 1                    # começa em 1
while contador <= 5:            # repete ENQUANTO a condição for verdadeira
    print(contador)             # mostra o valor atual
    contador = contador + 1     # sem esta linha o laço nunca terminaria!
print("Fim")                    # executa quando a condição fica falsa
