# Aula 25 – Nível 1: Tamanho e maiúsculas
# teste: Concreto
palavra = input("Palavra: ")              # lê o texto
print("Letras:", len(palavra))            # len: quantidade de caracteres
print("Maiúsculas:", palavra.upper())     # upper: tudo em maiúsculas
print("Minúsculas:", palavra.lower())     # lower: tudo em minúsculas
print("Primeira letra:", palavra[0])      # posição 0 = primeiro caractere
