# Aula 26 – Nível 1: Uma lista de cores
# teste: 
cores = ["vermelho", "verde", "azul"]   # lista com 3 textos, entre colchetes
print(cores[0])                         # índice 0 = primeiro elemento
print(cores[-1])                        # índice -1 = último elemento
print(len(cores))                       # quantidade de elementos: 3
cores.append("amarelo")                 # append acrescenta no fim
print(cores)                            # mostra a lista inteira
