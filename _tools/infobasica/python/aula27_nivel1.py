# teste: 
notas = [7.5, 8.0, 6.5, 9.0]                 # lista de notas
print("Soma:", sum(notas))                   # sum soma todos os elementos
print("Média:", sum(notas) / len(notas))     # soma ÷ quantidade
print("Maior:", max(notas))                  # max: maior elemento
print("Menor:", min(notas))                  # min: menor elemento
print("Ordenadas:", sorted(notas))           # sorted: nova lista em ordem crescente
