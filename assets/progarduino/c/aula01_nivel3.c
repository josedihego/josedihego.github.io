// Aula 1 – Nível 3: Cartão com moldura
#include <stdio.h>                                // printf

int main(void) {                                  // início do programa
    printf("+--------------------------+\n");     // borda de cima
    printf("| Nome:  Ana Souza         |\n");     // conteúdo do cartão
    printf("| Curso: Automação         |\n");     // mostra "| Curso: Automação         |"
    printf("| Lema:  \"Medir é saber\"   |\n");   // \" escreve aspas dentro do texto
    printf("| Progresso: 100%%          |\n");     // %% escreve o símbolo de porcentagem
    printf("+--------------------------+\n");     // borda de baixo
    return 0;                                     // sucesso
}
